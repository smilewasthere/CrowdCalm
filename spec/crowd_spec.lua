describe("Crowd", function()
  local ns = stub.newNs()
  stub.loadAddon("Crowd.lua", ns)

  local function newCrowd()
    return ns.Crowd.new({ high = 15, low = 10, enterDelay = 3, exitDelay = 5 })
  end

  it("enters crowd mode only after the enter delay", function()
    local c = newCrowd()
    expect(c:Update(0, 20)):toBe("normal")
    expect(c:Update(2.9, 20)):toBe("normal")
    expect(c:Update(3.1, 20)):toBe("crowd")
  end)

  it("exits crowd mode only after the exit delay", function()
    local c = newCrowd()
    c:Update(0, 20)
    c:Update(3.1, 20)
    expect(c:GetMode()):toBe("crowd")
    expect(c:Update(10, 12)):toBe("crowd")
    expect(c:Update(20, 8)):toBe("crowd")
    expect(c:Update(24.9, 5)):toBe("crowd")
    expect(c:Update(25.1, 5)):toBe("normal")
  end)

  it("resets the enter timer when the count drops below high", function()
    local c = newCrowd()
    c:Update(0, 20)
    c:Update(2, 5)
    c:Update(4, 20)
    expect(c:Update(6.9, 20)):toBe("normal")
    expect(c:Update(7.1, 20)):toBe("crowd")
  end)

  it("treats the high and low boundaries as inclusive", function()
    local c = newCrowd()
    c:Update(0, 15)
    expect(c:Update(3.1, 15)):toBe("crowd")
    c:Update(10, 10)
    expect(c:Update(15.1, 10)):toBe("normal")
  end)

  it("Reset returns to normal and clears pending timers", function()
    local c = newCrowd()
    c:Update(0, 20)
    c:Reset(2)
    expect(c:Update(4.5, 20)):toBe("normal")
    expect(c:Update(7.4, 20)):toBe("normal")
    expect(c:Update(7.6, 20)):toBe("crowd")
  end)
end)
